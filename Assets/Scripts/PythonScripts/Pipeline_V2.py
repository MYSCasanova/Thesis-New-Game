# ============================================================
# PHASE 3 — RULE-BASED LABELING
# ============================================================

COMPLETION_Q1 = np.percentile(completion_time, 25)
COMPLETION_Q3 = np.percentile(completion_time, 75)

ERROR_Q1 = np.percentile(error_count, 25)
ERROR_Q3 = np.percentile(error_count, 75)

def classify_completion_time(value):
    if value < COMPLETION_Q1:
        return "LOW"
    elif value <= COMPLETION_Q3:
        return "MEDIUM"
    else:
        return "HIGH"

def classify_error_count(value):
    if value <= ERROR_Q1:
        return "LOW"
    elif value <= ERROR_Q3:
        return "MEDIUM"
    else:
        return "HIGH"

def determine_final_label(completion_class, error_class):
    if completion_class == "LOW" and error_class == "LOW":
        return "LOW"
    elif completion_class == "HIGH" and error_class == "HIGH":
        return "HIGH"
    else:
        return "MEDIUM"

