def descriptive_statistics(values):

    return {
        "N": len(values),
        "Mean": np.mean(values),
        "Median": np.median(values),
        "Sample SD": np.std(values, ddof=1),
        "Minimum": np.min(values),
        "Q1 (25%)": np.percentile(values, 25),
        "Q3 (75%)": np.percentile(values, 75),
        "Maximum": np.max(values)
    }

