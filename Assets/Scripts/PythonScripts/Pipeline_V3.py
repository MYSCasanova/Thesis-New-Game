# 1. Define the final verified C4.5 decision-tree rules from the thesis
def apply_c45_rules(row):
    # Root node
    if row["platform_brightness"] <= 0.205:
        return "HIGH"
    # Second-level node
    if row["platform_brightness"] <= 0.665:
        return "MEDIUM"
    # Third-level node
    if row["platform_contrast"] <= 0.765:
        return "LOW"
    # Final terminal leaf
    return "MEDIUM"

