"""# **PHASE 5 — RELIEFF**
"""

# ============================================================
# RELIEFF — CREATE GROUND-TRUTH LABELS
# ============================================================

labels = np.array([
    determine_final_label(c, e)
    for c, e in zip(completion_labels, error_labels)
])

# ============================================================
# RELIEFF — CELL 1
# ============================================================

m = X.shape[0]
num_features = X.shape[1]
k = 3
classes = np.array(["LOW", "MEDIUM", "HIGH"])

feature_min = X.min(axis=0)
feature_max = X.max(axis=0)
feature_range = feature_max - feature_min

class_counts = {
    class_name: int(np.sum(labels == class_name))
    for class_name in classes
}

class_probabilities = {
    class_name: class_counts[class_name] / m
    for class_name in classes
}

# ============================================================
# RELIEFF — CELL 2 & 3: DIFFERENCES AND DISTANCES
# ============================================================

def relief_difference(value_i, value_j, feature_index):
    feature_range_value = feature_range[feature_index]
    if feature_range_value == 0:
        return 0.0
    return abs(value_i - value_j) / feature_range_value

def all_feature_differences(instance_i, instance_j):
    return np.array([
        relief_difference(instance_i[i], instance_j[i], i)
        for i in range(len(feature_names))
    ], dtype=float)

def relief_distance(instance_i, instance_j):
    return np.sum(all_feature_differences(instance_i, instance_j))

num_participants = m
distance_matrix = np.zeros((num_participants, num_participants))

for i in range(num_participants):
    for j in range(num_participants):
        if i == j:
            distance_matrix[i, j] = np.inf
        else:
            distance_matrix[i, j] = relief_distance(X[i], X[j])

# ============================================================
# RELIEFF — CELL 4: FIND NEAREST HITS AND MISSES
# ============================================================

def find_nearest_hits_and_misses(participant_index):
    current_class = labels[participant_index]
    other_indices = [i for i in range(num_participants) if i != participant_index]
    
    hit_candidates = [i for i in other_indices if labels[i] == current_class]
    hit_candidates_sorted = sorted(hit_candidates, key=lambda i: distance_matrix[participant_index, i])
    nearest_hits = hit_candidates_sorted[:k]
    
    nearest_misses = {}
    for class_name in classes:
        if class_name == current_class:
            continue
        miss_candidates = [i for i in other_indices if labels[i] == class_name]
        miss_candidates_sorted = sorted(miss_candidates, key=lambda i: distance_matrix[participant_index, i])
        nearest_misses[class_name] = miss_candidates_sorted[:k]
        
    return nearest_hits, nearest_misses

nearest_neighbors = {}
for i in range(num_participants):
    hits, misses = find_nearest_hits_and_misses(i)
    nearest_neighbors[i] = {"hits": hits, "misses": misses}

# ============================================================
# RELIEFF — CELL 6 & 7: CALCULATE WEIGHTS
# ============================================================

def calculate_relief_contribution(participant_index):
    current_class = labels[participant_index]
    hits = nearest_neighbors[participant_index]["hits"]
    misses = nearest_neighbors[participant_index]["misses"]
    
    hit_sum = np.zeros(num_features, dtype=float)
    for n_idx in hits:
        hit_sum += all_feature_differences(X[participant_index], X[n_idx])
    hit_contribution = hit_sum / (m * k)
    
    total_miss_contribution = np.zeros(num_features, dtype=float)
    current_class_probability = class_probabilities[current_class]
    
    for class_name in classes:
        if class_name == current_class:
            continue
        class_misses = misses[class_name]
        miss_sum = np.zeros(num_features, dtype=float)
        for n_idx in class_misses:
            miss_sum += all_feature_differences(X[participant_index], X[n_idx])
            
        probability_factor = class_probabilities[class_name] / (1.0 - current_class_probability)
        total_miss_contribution += (probability_factor * miss_sum / (m * k))
        
    final_contribution = -hit_contribution + total_miss_contribution
    return final_contribution

all_contributions = np.zeros((num_participants, num_features))
for i in range(num_participants):
    all_contributions[i] = calculate_relief_contribution(i)

relief_weights = np.sum(all_contributions, axis=0)

relief_results = pd.DataFrame({
    "Feature": feature_names,
    "ReliefF Weight": relief_weights
}).sort_values("ReliefF Weight", ascending=False).reset_index(drop=True)

